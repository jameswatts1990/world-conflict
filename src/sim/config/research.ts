// Research tree: six branches across four eras (eight columns, two per era).
// Effects are declarative so the UI can describe them and the sim can apply
// them. The tree is longer than a campaign: nations must choose a direction.
import type { Effect, Era, PartialResources, TechBranch, TechId, UnitType } from '../types';

export interface TechConfig {
  id: TechId;
  name: string;
  branch: TechBranch;
  /** Column 0–7; two columns per era. */
  col: number;
  /** Row within the branch (0–2), for the tree layout. */
  row: number;
  description: string;
  requires: TechId[];
  cost: PartialResources;
  seconds: number;
  effects: Effect[];
}

