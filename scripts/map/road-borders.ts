// Writes src/sim/scenario/europe/roads.ts: where each road between two lands crosses their border
// (see roads.ts). Run after the map changes; tests/scenario.test.ts checks the file against the map.
//
//   npx vite-node scripts/map/road-borders.ts   # also run by `npm run map:build`
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { roadBorders } from './roads';

const root = process.cwd();
const topo = JSON.parse(readFileSync(join(root, 'src', 'assets', 'map', 'map.topo.json'), 'utf8'));
const lines = Object.entries(roadBorders(topo)).map(([k, v]) => `  '${k}': ${v},`);
writeFileSync(
  join(root, 'src', 'sim', 'scenario', 'europe', 'roads.ts'),
  [
    '// Generated by scripts/map/road-borders.ts from the map shapes: do not edit by hand.',
    "// For each road between two lands, keyed as its connection is written ('a|b'): how far from a's land",
    "// towards b's (0..1, along the straight line between their anchors) the road crosses into b's land.",
    'export const ROAD_BORDERS: Record<string, number> = {',
    ...lines,
    '};',
    '',
  ].join('\n'),
);
console.log(`${lines.length} roads written to src/sim/scenario/europe/roads.ts`);
