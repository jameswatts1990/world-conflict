// Writes src/sim/scenario/europe/roads.ts: where each road between two provinces runs on the map and, between
// two lands, where it crosses their border (see roads.ts). Run after the map changes; tests/scenario.test.ts
// checks the file against the map.
//
//   npx vite-node scripts/map/road-routes.ts   # also run by `npm run map:build`
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { landId } from '../../src/sim/scenario/build';
import { LAND, LINKS } from '../../src/sim/scenario/europe/land';
import { ROWS } from '../../src/sim/scenario/europe/provinces';
import { roadFaults, roadRoutes, type MapTopology } from './roads';

const root = process.cwd();
const topo = JSON.parse(readFileSync(join(root, 'src', 'assets', 'map', 'map.topo.json'), 'utf8')) as MapTopology;
const anchors: Record<string, [number, number]> = {};
for (const row of ROWS) anchors[row.id] = row.city.coord;
for (const [row, { lands }] of Object.entries(LAND)) for (const l of lands) anchors[landId(row, l.key)] = l.anchor;
const cities = new Set(ROWS.map((r) => r.id));
const roads = roadRoutes(topo, LINKS, anchors, cities);
const lines = Object.entries(roads)
  .filter(([, r]) => r.border !== undefined || r.via)
  .map(([k, r]) => {
    const parts = [...(r.border !== undefined ? [`border: ${r.border}`] : []), ...(r.via ? [`via: [${r.via.map(([x, y]) => `[${x}, ${y}]`).join(', ')}]`] : [])];
    return `  '${k}': { ${parts.join(', ')} },`;
  });
writeFileSync(
  join(root, 'src', 'sim', 'scenario', 'europe', 'roads.ts'),
  [
    '// Generated by scripts/map/road-routes.ts from the map shapes: do not edit by hand.',
    "// For each link between provinces, keyed as it is written ('a|b'): where its road bends on its way from a's",
    "// anchor to b's ([longitude, latitude]; none where it runs straight), keeping to the two provinces, and for a",
    "// road between two lands, how far from a's anchor towards b's (0..1, along the road) it crosses into b's land.",
    "import type { RoadData } from '../build';",
    '',
    'export const ROADS: Record<string, RoadData> = {',
    ...lines,
    '};',
    '',
  ].join('\n'),
);
const bent = Object.values(roads).filter((r) => r.via).length;
console.log(`${LINKS.length} roads (${bent} bent round what lay between their anchors) written to src/sim/scenario/europe/roads.ts`);
// Where the shapes leave a road no way that keeps to its two provinces, say so (tests/scenario.test.ts lists them).
for (const f of roadFaults(topo, LINKS, anchors, cities, roads))
  if (f.third || f.sea || f.back) console.log(`  ${f.link}: ${f.third} km through other provinces, ${f.sea} km over water, ${f.back} km back over its border`);
